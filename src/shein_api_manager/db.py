def connect(database_url: str) -> psycopg.Connection:
    return psycopg.connect(database_url)


def schema_database_url(database_url: str, schema_name: str) -> str:
    schema_name = schema_name.strip()
    if not SCHEMA_NAME_PATTERN.fullmatch(schema_name):
        raise ValueError("invalid PostgreSQL shop schema")
    return make_conninfo(database_url, options=f"-csearch_path={schema_name},public")


@lru_cache(maxsize=32)
def shop_database_url(database_url: str, shop_key: str) -> str:
    shop_key = shop_key.strip()
    if not SHOP_CODE_PATTERN.fullmatch(shop_key):
        raise ValueError("invalid SHEIN shop code")
    with psycopg.connect(database_url) as conn:
        row = conn.execute(
            """
            SELECT schema_name
            FROM public.shein_shops
            WHERE shop_key = %s AND enabled = true
            """,
            (shop_key,),
        ).fetchone()
    if not row:
        raise KeyError(f"shop_key not found or disabled in public.shein_shops: {shop_key}")
    return schema_database_url(database_url, str(row[0]))


def list_registered_shops(database_url: str, *, enabled_only: bool = False) -> list[dict[str, Any]]:
    query = """
        SELECT shop_key, shop_name, schema_name, enabled, created_at, updated_at
        FROM public.shein_shops
    """
    if enabled_only:
        query += " WHERE enabled = true"
    query += " ORDER BY shop_name, shop_key"
    with psycopg.connect(database_url) as conn:
        rows = conn.execute(query).fetchall()
    return [
        {
            "shop_key": row[0],
            "shop_name": row[1],
            "schema_name": row[2],
            "enabled": bool(row[3]),
            "created_at": row[4],
            "updated_at": row[5],
        }
        for row in rows
    ]


def init_registry(database_url: str) -> None:
    with psycopg.connect(database_url) as conn:
        conn.execute(REGISTRY_SCHEMA_SQL)
    shop_database_url.cache_clear()


def init_shop_schema(database_url: str, shop_key: str) -> None:
    target_url = shop_database_url(database_url, shop_key)
    with connect(target_url) as conn:
        conn.execute(SHOP_SCHEMA_SQL)
        conn.execute(INVENTORY_SCHEMA_SQL)


def init_db(database_url: str, *, shop_key: str | None = None) -> None:
    init_registry(database_url)
    shops = list_registered_shops(database_url, enabled_only=True)
    if shop_key is not None:
        shops = [shop for shop in shops if shop["shop_key"] == shop_key]
        if not shops:
            raise KeyError(f"shop_key not found or disabled in public.shein_shops: {shop_key}")
    with psycopg.connect(database_url) as conn:
        for shop in shops:
            schema_name = str(shop["schema_name"])
            if not SCHEMA_NAME_PATTERN.fullmatch(schema_name):
                raise ValueError(f"invalid PostgreSQL schema for shop {shop['shop_key']}")
            conn.execute(sql.SQL("CREATE SCHEMA IF NOT EXISTS {}").format(sql.Identifier(schema_name)))
    for shop in shops:
        init_shop_schema(database_url, str(shop["shop_key"]))


