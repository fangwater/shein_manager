def bulk_upsert_warehouse_skus(database_url: str, *, shop_key: str, warehouse_skus: list[str]) -> dict[str, Any]:
    inserted = 0
    updated = 0
    skipped = 0
    rows: list[dict[str, Any]] = []
    seen: set[str] = set()
    for raw in warehouse_skus:
        sku = normalize_warehouse_sku_value(raw)
        if not sku or sku in seen:
            skipped += 1
            continue
        seen.add(sku)
        row, is_inserted = upsert_warehouse_sku(
            database_url,
            shop_key=shop_key,
            warehouse_sku=sku,
            preserve_existing_values=True,
        )
        rows.append(row)
        inserted += 1 if is_inserted else 0
        updated += 0 if is_inserted else 1
    return {"inserted": inserted, "updated": updated, "skipped": skipped, "rows": rows}


