def get_order_full_sync_summary(database_url: str, *, job_id: int) -> dict[str, Any]:
    with connect(database_url) as conn:
        row = conn.execute(
            """
            SELECT
                j.id,
                j.sync_key,
                j.status,
                COUNT(w.id) AS windows_total,
                COUNT(w.id) FILTER (WHERE w.status = 'success') AS windows_completed,
                COALESCE(SUM(w.pages), 0) AS pages,
                COALESCE(SUM(w.orders_seen), 0) AS orders_seen,
                COALESCE(SUM(w.orders_upserted), 0) AS orders_upserted,
                COALESCE(SUM(w.details_fetched), 0) AS details_fetched,
                j.last_error
            FROM shein_order_full_sync_jobs j
            LEFT JOIN shein_order_full_sync_windows w ON w.job_id = j.id
            WHERE j.id = %s
            GROUP BY j.id
            """,
            (job_id,),
        ).fetchone()
    if not row:
        raise KeyError(f"full sync job not found: {job_id}")
    return {
        "jobId": int(row[0]),
        "syncKey": row[1],
        "status": row[2],
        "windowsTotal": int(row[3]),
        "windowsCompleted": int(row[4]),
        "pages": int(row[5]),
        "ordersSeen": int(row[6]),
        "ordersInserted": int(row[7]),
        "detailsFetched": int(row[8]),
        "error": row[9],
    }


