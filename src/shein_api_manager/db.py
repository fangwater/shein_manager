def list_product_sku_options(database_url: str, *, shop_key: str) -> list[dict[str, Any]]:
    ensure_product_schema(database_url)
    options: dict[str, dict[str, Any]] = {}
    with connect(database_url) as conn:
        product_rows = conn.execute(
            """
            SELECT spu_name, skc_name, sku_code_list, raw_payload, last_seen_at
            FROM shein_products
            WHERE shop_key = %s
            ORDER BY last_seen_at DESC, spu_name, skc_name
            """,
            (shop_key,),
        ).fetchall()
        detail_rows = conn.execute(
            """
            SELECT spu_name, skc_list, raw_payload, last_seen_at
            FROM shein_product_details
            WHERE shop_key = %s
            ORDER BY last_seen_at DESC, spu_name
            """,
            (shop_key,),
        ).fetchall()

    for row in product_rows:
        spu_name = _text_or_none(row[0])
        skc_name = _text_or_none(row[1])
        for sku_code in _json_string_list(row[2]):
            _remember_product_sku_option(
                options,
                sku_code=sku_code,
                spu_name=spu_name,
                skc_name=skc_name,
                last_seen_at=row[4],
            )

    for row in detail_rows:
        spu_name = _text_or_none(row[0])
        skc_items = row[1] if isinstance(row[1], list) else []
        for skc in skc_items:
            if not isinstance(skc, dict):
                continue
            skc_name = _text_or_none(skc.get("skcName") or skc.get("skc_name"))
            title = _localized_product_text(skc.get("skcTitle"), "title")
            supplier_code = _text_or_none(skc.get("supplierCode") or skc.get("supplier_code"))
            main_pic_url = _text_or_none(skc.get("skcMainPicUrl") or skc.get("skc_main_pic_url"))
            sku_items = skc.get("skuList") if isinstance(skc.get("skuList"), list) else []
            for sku in sku_items:
                if not isinstance(sku, dict):
                    continue
                sku_code = _text_or_none(sku.get("skuCode") or sku.get("sku_code"))
                if not sku_code:
                    continue
                _remember_product_sku_option(
                    options,
                    sku_code=sku_code,
                    spu_name=spu_name,
                    skc_name=skc_name,
                    supplier_code=supplier_code,
                    supplier_sku=_text_or_none(sku.get("supplierSku") or sku.get("supplier_sku")),
                    title=title,
                    main_pic_url=main_pic_url,
                    last_seen_at=row[3],
                )
    return sorted(options.values(), key=lambda item: (item.get("title") or "", item["sku_code"]))


def _remember_product_sku_option(
    options: dict[str, dict[str, Any]],
    *,
    sku_code: str,
    spu_name: str | None = None,
    skc_name: str | None = None,
    supplier_code: str | None = None,
    supplier_sku: str | None = None,
    title: str | None = None,
    main_pic_url: str | None = None,
    last_seen_at: Any = None,
) -> None:
    existing = options.setdefault(
        sku_code,
        {
            "sku_code": sku_code,
            "spu_name": None,
            "skc_name": None,
            "supplier_code": None,
            "supplier_sku": None,
            "title": None,
            "main_pic_url": None,
            "last_seen_at": None,
        },
    )
    for key, value in {
        "spu_name": spu_name,
        "skc_name": skc_name,
        "supplier_code": supplier_code,
        "supplier_sku": supplier_sku,
        "title": title,
        "main_pic_url": main_pic_url,
        "last_seen_at": last_seen_at,
    }.items():
        if value not in (None, ""):
            existing[key] = value


def _json_string_list(value: Any) -> list[str]:
    if not isinstance(value, list):
        return []
    return [str(item).strip() for item in value if str(item or "").strip()]


def _text_or_none(value: Any) -> str | None:
    if value in (None, ""):
        return None
    text = str(value).strip()
    return text or None


def _localized_product_text(value: Any, key: str) -> str | None:
    if not isinstance(value, list):
        return None
    preferred = ("zh-cn", "en", "fr", "es", "de", "pt-br", "th", "ja", "ko")
    by_language: dict[str, str] = {}
    fallback: str | None = None
    for item in value:
        if not isinstance(item, dict):
            continue
        text = _text_or_none(item.get(key))
        if not text:
            continue
        language = str(item.get("language") or "").lower()
        if language:
            by_language[language] = text
        fallback = fallback or text
    for language in preferred:
        if language in by_language:
            return by_language[language]
    return fallback

