def ensure_order_full_sync_job(
    database_url: str,
    *,
    shop_key: str,
    sync_key: str,
    query_type: int,
    start_time: str,
    end_time: str,
    base_params: dict[str, Any],
    window_hours: float,
    list_rps: float,
    detail_rps: float,
    reset: bool = False,
) -> int:
    with connect(database_url) as conn:
        row = conn.execute(
            """
            SELECT id, query_type, start_time, end_time, base_params
            FROM shein_order_full_sync_jobs
            WHERE shop_key = %s AND sync_key = %s
            """,
            (shop_key, sync_key),
        ).fetchone()
        if row:
            job_id = int(row[0])
            same_parameters = (
                int(row[1]) == query_type
                and row[2] == start_time
                and row[3] == end_time
                and (row[4] or {}) == base_params
            )
            if not same_parameters and not reset:
                raise ValueError(
                    "sync_key already exists with different parameters; use another --sync-key or pass --reset"
                )
            if reset:
                conn.execute("DELETE FROM shein_order_full_sync_windows WHERE job_id = %s", (job_id,))
                conn.execute(
                    """
                    UPDATE shein_order_full_sync_jobs
                    SET query_type = %s,
                        start_time = %s,
                        end_time = %s,
                        base_params = %s,
                        status = 'running',
                        finished_at = NULL,
                        updated_at = now(),
                        last_error = NULL,
                        window_hours = %s,
                        list_rps = %s,
                        detail_rps = %s
                    WHERE id = %s
                    """,
                    (
                        query_type,
                        start_time,
                        end_time,
                        Jsonb(base_params),
                        window_hours,
                        list_rps,
                        detail_rps,
                        job_id,
                    ),
                )
            else:
                conn.execute(
                    """
                    UPDATE shein_order_full_sync_jobs
                    SET status = CASE WHEN status = 'success' THEN status ELSE 'running' END,
                        finished_at = CASE WHEN status = 'success' THEN finished_at ELSE NULL END,
                        updated_at = now(),
                        last_error = CASE WHEN status = 'success' THEN last_error ELSE NULL END,
                        window_hours = %s, list_rps = %s, detail_rps = %s
                    WHERE id = %s
                    """,
                    (window_hours, list_rps, detail_rps, job_id),
                )
            return job_id

        row = conn.execute(
            """
            INSERT INTO shein_order_full_sync_jobs (
                shop_key, sync_key, query_type, start_time, end_time, base_params,
                window_hours, list_rps, detail_rps, status
            )
            VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, 'running')
            RETURNING id
            """,
            (
                shop_key,
                sync_key,
                query_type,
                start_time,
                end_time,
                Jsonb(base_params),
                window_hours,
                list_rps,
                detail_rps,
            ),
        ).fetchone()
    return int(row[0])


